static async Task EnsureAdminBootstrapAsync(IServiceProvider services, IConfiguration configuration, ILogger logger)
{
    var bootstrapSection = configuration.GetSection("AdminBootstrap");
    var enabled = bootstrapSection.GetValue<bool>("Enabled");
    if (!enabled)
    {
        return;
    }

    var configuredEmail = bootstrapSection["Email"];
    var password = bootstrapSection["Password"];
    var fullName = bootstrapSection["FullName"]?.Trim();

    if (ConfigurationValueGuards.IsPlaceholder(configuredEmail)
        || ConfigurationValueGuards.IsPlaceholder(password))
    {
        logger.LogWarning("AdminBootstrap uses placeholder values. Set ADMIN_BOOTSTRAP__EMAIL and ADMIN_BOOTSTRAP__PASSWORD environment variables.");
        return;
    }

    if (!ConfigurationValueGuards.HasConfiguredValue(configuredEmail)
        || !ConfigurationValueGuards.HasConfiguredValue(password))
    {
        logger.LogWarning("AdminBootstrap is enabled but Email/Password is missing.");
        return;
    }

    var email = configuredEmail!.Trim().ToLowerInvariant();
    using var scope = services.CreateScope();
    var context = scope.ServiceProvider.GetRequiredService<ApplicationDbContext>();

    var existing = await context.Users.FirstOrDefaultAsync(u => u.Email == email);
    if (existing is not null)
    {
        var needsSave = false;

        if (existing.Role != UserRole.Admin)
        {
            existing.Role = UserRole.Admin;
            existing.Status = UserStatus.Active;
            existing.CanLogin = true;
            existing.UpdatedAt = DateTime.UtcNow;
            needsSave = true;
        }

        if (!BCrypt.Net.BCrypt.Verify(password, existing.PasswordHash))
        {
            existing.PasswordHash = BCrypt.Net.BCrypt.HashPassword(password);
            existing.UpdatedAt = DateTime.UtcNow;
            needsSave = true;
        }

        if (needsSave)
        {
            await context.SaveChangesAsync();
        }

        return;
    }

    var now = DateTime.UtcNow;
    context.Users.Add(new User
    {
        Email = email,
        PasswordHash = BCrypt.Net.BCrypt.HashPassword(password),
        FullName = string.IsNullOrWhiteSpace(fullName) ? "Admin" : fullName,
        Role = UserRole.Admin,
        Status = UserStatus.Active,
        CanLogin = true,
        CreatedAt = now,
        UpdatedAt = now
    });

    await context.SaveChangesAsync();
    logger.LogInformation("Development admin user bootstrapped: {Email}", email);
}

static async Task EnsureDatabaseReadyAsync(IServiceProvider services, ILogger logger)
{
    using var scope = services.CreateScope();
    var context = scope.ServiceProvider.GetRequiredService<ApplicationDbContext>();

    if (!context.Database.IsRelational())
    {
        return;
    }

    try
    {
        await context.Database.MigrateAsync();
    }
    catch (Exception ex)
    {
        logger.LogError(ex, "Database migration failed during startup.");
        throw;
    }
}

static void ConfigureDatabase(
    IConfiguration configuration,
    IWebHostEnvironment environment,
    IServiceCollection services,
    out bool usingInMemoryDatabaseFallback,
    out string? fallbackReason)
{
    var connectionString = configuration.GetConnectionString("DefaultConnection");
    var hasConfiguredConnectionString = ConfigurationValueGuards.HasConfiguredValue(connectionString);
    var fallbackEnabled = environment.IsDevelopment()
        && configuration.GetValue("Database:EnableInMemoryFallback", false);
    var probeTimeoutSeconds = Math.Max(1, configuration.GetValue("Database:ConnectionProbeTimeoutSeconds", 3));

    if (fallbackEnabled
        && !CanConnectToSqlServer(connectionString, probeTimeoutSeconds, out fallbackReason))
    {
        var databaseName = configuration["Database:InMemoryDatabaseName"]?.Trim();
        if (string.IsNullOrWhiteSpace(databaseName))
        {
            databaseName = "mototun-dev";
        }

        services.AddDbContext<ApplicationDbContext>(options =>
            options.UseInMemoryDatabase(databaseName));
        usingInMemoryDatabaseFallback = true;
        return;
    }

    if (!hasConfiguredConnectionString)
    {
        throw new InvalidOperationException("ConnectionStrings:DefaultConnection is not configured.");
    }

    services.AddDbContext<ApplicationDbContext>(options =>
        options.UseSqlServer(connectionString));
    usingInMemoryDatabaseFallback = false;
    fallbackReason = null;
}

static bool CanConnectToSqlServer(string? connectionString, int timeoutSeconds, out string? failureReason)
{
    if (!ConfigurationValueGuards.HasConfiguredValue(connectionString))
    {
        failureReason = "Connection string is missing.";
        return false;
    }

    try
    {
        var builder = new SqlConnectionStringBuilder(connectionString)
        {
            ConnectTimeout = timeoutSeconds
        };

        using var connection = new SqlConnection(builder.ConnectionString);
        connection.Open();
        failureReason = null;
        return true;
    }
    catch (Exception ex)
    {
        failureReason = ex.Message;
        return false;
    }
}

