static HashSet<string> LoadCorsAllowedOrigins(IConfiguration configuration)
{
    var configuredOrigins = configuration.GetSection("Cors:AllowedOrigins").Get<string[]>() ?? Array.Empty<string>();
    var normalizedOrigins = new HashSet<string>(StringComparer.OrdinalIgnoreCase);

    foreach (var origin in configuredOrigins)
    {
        var normalizedOrigin = NormalizeCorsOrigin(origin);
        if (!string.IsNullOrWhiteSpace(normalizedOrigin))
        {
            normalizedOrigins.Add(normalizedOrigin);
        }
    }

    return normalizedOrigins;
}

static bool IsAllowedCorsOrigin(string origin, HashSet<string> configuredOrigins, bool isDevelopment)
{
    var normalizedOrigin = NormalizeCorsOrigin(origin);
    if (string.IsNullOrWhiteSpace(normalizedOrigin))
    {
        return false;
    }

    if (configuredOrigins.Contains(normalizedOrigin))
    {
        return true;
    }

    if (!isDevelopment || !Uri.TryCreate(normalizedOrigin, UriKind.Absolute, out var uri))
    {
        return false;
    }

    return uri.IsLoopback || uri.Host.Equals("localhost", StringComparison.OrdinalIgnoreCase);
}

static string BuildEmbeddablePreviewFrameAncestors(HashSet<string> configuredOrigins, bool isDevelopment)
{
    var allowedOrigins = configuredOrigins
        .Where(origin => !string.IsNullOrWhiteSpace(origin))
        .Distinct(StringComparer.OrdinalIgnoreCase)
        .ToList();

    if (isDevelopment)
    {
        foreach (var developmentOrigin in new[] { "http://localhost:5173", "http://127.0.0.1:5173" })
        {
            if (!allowedOrigins.Contains(developmentOrigin, StringComparer.OrdinalIgnoreCase))
            {
                allowedOrigins.Add(developmentOrigin);
            }
        }
    }

    return allowedOrigins.Count == 0
        ? "frame-ancestors 'self'"
        : $"frame-ancestors 'self' {string.Join(' ', allowedOrigins)}";
}

static bool IsEmbeddableDocumentPreviewPath(PathString path)
{
    if (!path.HasValue)
    {
        return false;
    }

    var value = path.Value ?? string.Empty;
    if (!value.EndsWith("/inline", StringComparison.OrdinalIgnoreCase))
    {
        return false;
    }

    return value.StartsWith("/api/Invoices/", StringComparison.OrdinalIgnoreCase)
        || value.StartsWith("/api/client-portal/", StringComparison.OrdinalIgnoreCase);
}

static string? NormalizeCorsOrigin(string? origin)
{
    if (string.IsNullOrWhiteSpace(origin))
    {
        return null;
    }

    if (!Uri.TryCreate(origin.Trim(), UriKind.Absolute, out var uri))
    {
        return null;
    }

    if (uri.Scheme != Uri.UriSchemeHttp && uri.Scheme != Uri.UriSchemeHttps)
    {
        return null;
    }

    return uri.GetLeftPart(UriPartial.Authority).TrimEnd('/');
}

static string ResolveJwtSecretKey(IConfiguration configuration, IWebHostEnvironment environment, out bool wasAutoGenerated)
{
    var configuredSecret = configuration["JwtSettings:SecretKey"]?.Trim();
    if (ConfigurationValueGuards.HasConfiguredValue(configuredSecret))
    {
        ValidateJwtSecret(configuredSecret!);
        wasAutoGenerated = false;
        return configuredSecret!;
    }

    if (!environment.IsDevelopment())
    {
        throw new InvalidOperationException("JWT SecretKey is not configured. Set JWT_SETTINGS__SECRET_KEY (preferred) or JwtSettings__SecretKey.");
    }

    wasAutoGenerated = true;
    return Convert.ToBase64String(RandomNumberGenerator.GetBytes(64));
}

static void ValidateJwtSecret(string secret)
{
    if (secret.Length < 32)
    {
        throw new InvalidOperationException("JWT SecretKey must be at least 32 characters long.");
    }
}

